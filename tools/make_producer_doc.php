        foreach ($m['options'] as $mo) {
            if ($mo['id'] === $oid) $names[$formOf[$m['code']]['name'] ?? $m['name']] = true;
        }
    }
    return count($names) === count($cat['forms']) ? 'всички' : implode(', ', array_keys($names));
};
