$constrOf = function (array $f, string $shape = '') use ($constrName): string {
    $sh = $shape !== '' ? $shape : $f['shape'];
    if ($sh === 'cross') return 'тава от 4 трапецовидни панела и дъно + стойка от две плочи на прорез';
    if ($sh === 'ringbowl') return 'валцуван пръстен + купа';
    if ($sh === 'plancha') return $shape === '' ? 'основа (кръгла – валцувана, квадратна – панели) + плоча' : 'валцувана основа + плоча';
    if ($sh === 'plancha_sq') return 'отделни панели + плоча';
    // за хотели и обекти (v10)
    if ($sh === 'bowl') return 'изтеглена купа + пояс от сегменти + крак';
    if ($sh === 'firetable') return 'отделни панели + плот с вградена купа';
    if ($sh === 'ringbench') return 'пейка от метални сегменти (седалка от дърво) + валцувано огнище';
    if ($sh === 'column') return 'отделни панели + тава за огъня горе';
    return $constrName[$f['construction'] ?? 'panels'];
};
// опции по група за модела: [код => опция]
